// Builds docs/supabase-setup.sql: every Drizzle migration in order, plus the bookkeeping rows
// Drizzle uses, so the file can be pasted into Supabase's SQL editor instead of running
// `pnpm db:migrate`, and a later `pnpm db:migrate` still knows these are applied.
// Re-run after `pnpm db:generate`:  node scripts/build-supabase-sql.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../packages/database/drizzle/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
const parts = [
  "-- YouTube Agent OS: full database setup for Supabase.",
  "-- Paste all of this into Supabase -> SQL Editor -> New query, then click Run. Safe to run once on an empty project.",
  "-- Generated by scripts/build-supabase-sql.mjs; do not edit by hand.",
  "",
  "BEGIN;",
  'CREATE SCHEMA IF NOT EXISTS "drizzle";',
  'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
];
for (const entry of journal.entries) {
  const sql = readFileSync(new URL(`${entry.tag}.sql`, dir), "utf8");
  const hash = createHash("sha256").update(sql).digest("hex");
  parts.push("", `-- ${entry.tag}`, sql.trim(), `INSERT INTO "drizzle"."__drizzle_migrations" (hash, created_at) VALUES ('${hash}', ${entry.when});`);
}
parts.push(
  "",
  "-- Supabase exposes the public schema through its Data API. The app talks to Postgres directly",
  "-- (and bypasses row level security), so lock every table to the Data API.",
  "DO $$ DECLARE t record; BEGIN",
  "  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP",
  "    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);",
  "  END LOOP;",
  "END $$;",
  "",
  "COMMIT;",
  "",
);
writeFileSync(new URL("../docs/supabase-setup.sql", import.meta.url), parts.join("\n"));
console.log(`Wrote docs/supabase-setup.sql (${journal.entries.length} migrations)`);
